from django.conf import settings
from django.db.models.signals import post_save
from django.dispatch import receiver
from rest_framework.authtoken.models import Token

@receiver(post_save, sender=settings.AUTH_USER_MODEL)
def create_auth_token(sender, instance=None, created=False, **kwargs):
    if created:
        Token.objects.create(user=instance) #This signal is triggered whenever a new user is created. It automatically generates an authentication token for the newly created user, allowing them to authenticate with the API using token-based authentication.